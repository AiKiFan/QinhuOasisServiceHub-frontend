/** 语言在 Storage 中的键名 */
const STORAGE_KEY_LANGUAGE = 'qinhu_language'

/** 默认语言 */
const DEFAULT_LANGUAGE = 'zh-CN'

/**
 * 保存语言偏好
 * @param {'zh-CN'|'en-US'} lang
 */
export function saveLanguage(lang) {
  uni.setStorageSync(STORAGE_KEY_LANGUAGE, lang)
}

/**
 * 读取语言偏好，未设置时返回默认值
 * @returns {'zh-CN'|'en-US'}
 */
export function getLanguage() {
  return uni.getStorageSync(STORAGE_KEY_LANGUAGE) || DEFAULT_LANGUAGE
}

/**
 * 切换语言（中文 ↔ 英文）
 * @returns {'zh-CN'|'en-US'} 切换后的语言
 */
export function toggleLanguage() {
  const current = getLanguage()
  const next = current === 'zh-CN' ? 'en-US' : 'zh-CN'
  saveLanguage(next)
  return next
}

